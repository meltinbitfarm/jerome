// `jerome prompt`: the briefing instructions for any chat (D34). They are built from the same files the
// project-brief skill reads, so the two never drift apart.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { TEMPLATE_DIR, VERSION } from './template.js';

const REFERENCES = join(TEMPLATE_DIR, '.claude', 'skills', 'project-brief', 'references');

// The format file ends with sections about importing into a project, which only matter in Claude Code.
const FORMAT_END = '\n## Import\n';
const AREA_BRIEFING = '\n## Area briefing\n';

export function briefingPrompt() {
  // The area briefing works on an existing project's files: it stays in Claude Code (P5).
  const briefing = readFileSync(join(REFERENCES, 'briefing.md'), 'utf8').split(AREA_BRIEFING)[0].trim();
  const format = readFileSync(join(REFERENCES, 'brief-v3.md'), 'utf8');
  const end = format.indexOf(FORMAT_END);
  if (end === -1) throw new Error('brief-v3.md has no "## Import" section: the format part cannot be told apart');
  return `You are going to run a project briefing with me. Follow the instructions below.
When I ask to save or close the brief, write it in a single markdown block in the brief/v3 format, with nothing else inside the block, so I can copy it and import it with \`jerome new <name> --from-file -\`.
(Instructions generated by Jérôme ${VERSION}.)

${briefing}

${format.slice(0, end).trim()}
`;
}

export function prompt() {
  process.stdout.write(briefingPrompt());
  return 0;
}
